ItemEvents.modifyTooltips(event => {
  let skipped = 0
  for (let id in FORMULAS) {
    // Skip quietly if a mod was removed from the pack, instead of erroring on an unknown id.
    if (!Item.exists(id)) { skipped++; continue }
    let entry = FORMULAS[id]
    event.add(id, [Text.aqua(entry[0]).append(Text.gray(' · ' + entry[1]))])
  }
  if (skipped > 0) console.warn("formula_tooltips: skipped " + skipped + " ids that are not registered")
})
