#!/usr/bin/env python3
"""Regenerate docs/MODLIST.md from pack/mods/*.pw.toml + docs/modlist-meta.tsv.

Every mod in the pack must have a row in the TSV. The script fails if one is
missing, so the docs can't fall behind the pack. "Verified" means the mod is
in the packwiz pack (resolved to a NeoForge 1.21.1 file) and the last smoke
test passed with it.
"""
import csv
import pathlib
import re
import sys

ROOT = pathlib.Path(__file__).resolve().parent.parent
ORDER = ["Chemistry core", "Tech / Power", "Logistics / Storage", "World / Resources",
         "Magic", "Building", "FTB", "QoL", "Performance", "Library / Dependencies"]


def read_toml(p):
    t = p.read_text()
    get = lambda k: (re.search(rf'^{k} = "(.*)"', t, re.M) or [None, ""])[1]
    if "[update.curseforge]" in t:
        pid = re.search(r"project-id = (\d+)", t).group(1)
        link = f"[CurseForge](https://www.curseforge.com/projects/{pid})"
    elif "[update.modrinth]" in t:
        mid = re.search(r'mod-id = "(\w+)"', t).group(1)
        link = f"[Modrinth](https://modrinth.com/mod/{mid})"
    else:  # direct URL (e.g. the pack's own Warbucks Core mod, a GitHub release)
        link = f"[Download]({get('url')})"
    return {"name": get("name"), "file": get("filename"), "side": get("side"), "link": link}


def main():
    meta = {r["slug"]: r for r in csv.DictReader(open(ROOT / "docs/modlist-meta.tsv"), delimiter="\t")}
    mods = {p.name[:-len(".pw.toml")]: read_toml(p) for p in sorted((ROOT / "pack/mods").glob("*.pw.toml"))}
    missing = sorted(set(mods) - set(meta))
    if missing:
        sys.exit(f"Missing from docs/modlist-meta.tsv: {', '.join(missing)}")
    stale_meta = sorted(set(meta) - set(mods))

    out = ["# Mod List", "",
           f"**{len(mods)} mods** · NeoForge 21.1.262 · Minecraft 1.21.1 · generated by `test/gen_modlist.py` "
           "from the packwiz pack. Don't edit by hand; edit `docs/modlist-meta.tsv` instead.", "",
           "*Verified* = resolved by packwiz to a NeoForge 1.21.1 file and loaded in a passing smoke test.", ""]
    for cat in ORDER:
        rows = sorted((s for s in mods if meta[s]["category"] == cat), key=lambda s: mods[s]["name"].lower())
        if not rows:
            continue
        out += [f"## {cat} ({len(rows)})", "",
                "| Mod | Purpose | Tier | Verified NeoForge 1.21.1 | Source | Notes |",
                "|---|---|---|---|---|---|"]
        for s in rows:
            m, d = mods[s], meta[s]
            notes = "; ".join(x for x in [d["notes"], f"`{m['file']}`"] if x)
            out.append(f"| {m['name']} | {d['purpose']} | {d['tier'] or '—'} | yes | {m['link']} | {notes} |")
        out.append("")
    extra = ROOT / "docs/modlist-excluded.md"
    if extra.exists():
        out += [extra.read_text()]
    if stale_meta:
        out += ["<!-- metadata rows with no matching mod: " + ", ".join(stale_meta) + " -->"]
    (ROOT / "docs/MODLIST.md").write_text("\n".join(out) + "\n")
    print(f"Wrote docs/MODLIST.md ({len(mods)} mods)")


if __name__ == "__main__":
    main()
